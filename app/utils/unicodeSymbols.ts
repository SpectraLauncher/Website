export const codePoint = (symbol: string) =>
  'U+' + (symbol.codePointAt(0) ?? 0).toString(16).toUpperCase().padStart(4, '0')

export const escapeSeq = (symbol: string) =>
  Array.from(symbol)
    .flatMap((ch) => {
      const cp = ch.codePointAt(0) ?? 0
      if (cp <= 0xFFFF) return ['\\u' + cp.toString(16).toUpperCase().padStart(4, '0')]
      const h = Math.floor((cp - 0x10000) / 0x400) + 0xD800
      const l = ((cp - 0x10000) % 0x400) + 0xDC00
      return ['\\u' + h.toString(16).toUpperCase(), '\\u' + l.toString(16).toUpperCase()]
    })
    .join('')

